from style import *
fig, ax = canvas(11, 4.6)
T(ax, 5.5, 4.25, "ReLU：每做 1 个 FLOP，要搬多少字节", fontsize=15)
def row(y, name, nbytes, total, c, bg):
    T(ax, 0.9, y, name, fontsize=13, color=c)
    box(ax, 1.8, y-0.4, 2.2, 0.8, bg, c, lw=1.6); T(ax, 2.9, y, f"读 x：{nbytes} 字节", color=c)
    arrow(ax, (4.05, y), (4.65, y))
    box(ax, 4.7, y-0.4, 2.2, 0.8, "white", MUTE, lw=1.4); T(ax, 5.8, y, "比较 x < 0：1 FLOP")
    arrow(ax, (6.95, y), (7.55, y))
    box(ax, 7.6, y-0.4, 2.2, 0.8, bg, c, lw=1.6); T(ax, 8.7, y, f"写回：{nbytes} 字节", color=c)
    T(ax, 10.4, y, f"{total} 字节\n/ FLOP", fontsize=12.5, color=c)
row(3.2, "float32", 4, 8, B2, BG2)
row(2.0, "float16", 2, 4, B1, BG1)
box(ax, 0.3, 0.25, 10.4, 0.95, GR, LINE, r=0.12)
T(ax, 0.55, 0.9, "计算几乎为零，时间都花在搬数据上，所以速度由内存带宽决定。", ha="left", fontsize=11.5)
T(ax, 0.55, 0.52, "带宽不变时，每个元素的字节数减半，每秒能处理的元素数就翻倍。", ha="left", fontsize=11.5, color=OK)
save(fig, "07-relu-arithmetic-intensity.png")
